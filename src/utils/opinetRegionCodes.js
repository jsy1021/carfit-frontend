// 시군구 코드에서 시/도 코드 추출
export const getProvinceCodeFromRegionCode = (regionCode) => {
  return regionCode.substring(0, 2)
}

// 시군구 코드에서 시/도명 추출
export const getProvinceNameFromRegionCode = (regionCode) => {
  const provinceCode = getProvinceCodeFromRegionCode(regionCode)
  return getProvinceNameByCode(provinceCode)
}

// 특정 시/도의 모든 시군구 조회
export const getRegionsByProvinceCode = (provinceCode) => {
  return Object.entries(OPINET_REGION_CODES)
    .filter(([code, name]) => code.startsWith(provinceCode))
    .map(([code, name]) => ({ code, name }))
}

// 특정 시/도의 모든 시군구명 조회 (시/도 부분 제거)
export const getRegionNamesByProvinceCode = (provinceCode) => {
  return getRegionsByProvinceCode(provinceCode).map(item => {
    // "경기 파주시" -> "파주시"로 변환
    const provinceName = getProvinceNameByCode(provinceCode)
    if (item.name.startsWith(provinceName + ' ')) {
      return item.name.substring(provinceName.length + 1) // "경기 " 부분 제거
    }
    return item.name
  })
}
