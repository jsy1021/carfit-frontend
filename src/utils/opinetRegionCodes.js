// 코드로 지역명 조회
export const getRegionNameByCode = (code) => {
  return OPINET_REGION_CODES[code] || '알 수 없는 지역'
}

// 지역명으로 코드 조회
export const getCodeByRegionName = (regionName) => {
  const entry = Object.entries(OPINET_REGION_CODES).find(([code, name]) => name === regionName)
  return entry ? entry[0] : null
}

// 모든 지역 목록 반환
export const getAllRegions = () => {
  return Object.values(OPINET_REGION_CODES)
}

// 코드 목록 반환
export const getAllCodes = () => {
  return Object.keys(OPINET_REGION_CODES)
}

// 시/도 코드로 시/도명 조회
export const getProvinceNameByCode = (code) => {
  return OPINET_PROVINCE_CODES[code] || '알 수 없는 시/도'
}

// 시/도명으로 시/도 코드 조회
export const getCodeByProvinceName = (provinceName) => {
  const entry = Object.entries(OPINET_PROVINCE_CODES).find(([code, name]) => name === provinceName)
  return entry ? entry[0] : null
}

